"""
config.py - Central settings for IntelliDesk.

Every setting that may need tuning lives here, so we change a value in one
place and the whole project follows. This file contains no secrets, so it is
safe to commit to Git.
"""

from pathlib import Path

# ---------------------------------------------------------------------------
# 1. Application identity
# ---------------------------------------------------------------------------
APP_NAME = "IntelliDesk"
APP_TAGLINE = "AI-powered IT Helpdesk and Technical Support"
APP_DESCRIPTION = (
    "An AI-powered IT Helpdesk and Technical Support chatbot using a "
    "manually implemented RAG pipeline and a local LLM for intelligent, "
    "context-aware responses."
)

# ---------------------------------------------------------------------------
# 2. Folder and file locations
# ---------------------------------------------------------------------------
# __file__ is the location of this file (src/config.py).
# .parent gives src/, and .parent again gives the project root (IntelliDesk/).
PROJECT_ROOT = Path(__file__).resolve().parent.parent

DATA_DIR = PROJECT_ROOT / "data"
KNOWLEDGE_BASE_DIR = DATA_DIR / "knowledge_base"
SAMPLE_DOCS_DIR = KNOWLEDGE_BASE_DIR / "sample"
VERIFIED_DOCS_DIR = KNOWLEDGE_BASE_DIR / "verified"
INDEX_DIR = DATA_DIR / "index"                 # generated by build_index.py
DATABASE_PATH = DATA_DIR / "intellidesk.db"    # generated by database.py
EVALUATION_DIR = PROJECT_ROOT / "evaluation"

# ---------------------------------------------------------------------------
# 3. Knowledge base
# ---------------------------------------------------------------------------
# The folder a document sits in decides its label, so users can always tell
# sample demonstration content from verified university procedures.
LABEL_SAMPLE = "sample"
LABEL_VERIFIED = "verified"

KNOWLEDGE_BASE_FOLDERS = {
    LABEL_SAMPLE: SAMPLE_DOCS_DIR,
    LABEL_VERIFIED: VERIFIED_DOCS_DIR,
}

SUPPORTED_EXTENSIONS = (".pdf", ".txt")

# ---------------------------------------------------------------------------
# 4. Chunking (measured in words)
# ---------------------------------------------------------------------------
CHUNK_SIZE_WORDS = 120
CHUNK_OVERLAP_WORDS = 30

# ---------------------------------------------------------------------------
# 5. Retrieval
# ---------------------------------------------------------------------------
TOP_K = 3                      # how many best-matching chunks to retrieve
SIMILARITY_THRESHOLD = 0.15    # initial guess; we will tune it with real tests

# ---------------------------------------------------------------------------
# 6. Pipeline result statuses (the "contract" with app.py)
# ---------------------------------------------------------------------------
STATUS_ANSWERED = "answered"
STATUS_OUT_OF_SCOPE = "out_of_scope"
STATUS_NOT_FOUND = "not_found"

# ---------------------------------------------------------------------------
# 7. Local LLM (Ollama)
# ---------------------------------------------------------------------------
OLLAMA_BASE_URL = "http://localhost:11434"
OLLAMA_MODEL = "qwen3:1.7b"
OLLAMA_TEMPERATURE = 0.2        # low = more factual, less creative
OLLAMA_TIMEOUT_SECONDS = 120

# ---------------------------------------------------------------------------
# 8. Conversation
# ---------------------------------------------------------------------------
HISTORY_MESSAGES_IN_PROMPT = 6  # recent messages given to the LLM as context

# ---------------------------------------------------------------------------
# 9. Tickets
# ---------------------------------------------------------------------------
TICKET_CATEGORIES = [
    "Wi-Fi",
    "Student Portal",
    "University Email",
    "Software Installation",
    "Computer Lab",
    "LMS",
    "Account Security",
    "Other",
]
TICKET_STATUSES = ["Open", "In Progress", "Resolved"]
DEFAULT_TICKET_STATUS = TICKET_STATUSES[0]


# ---------------------------------------------------------------------------
# Quick self-check: run with  python -m src.config
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    print(f"{APP_NAME} configuration check")
    print("-" * 50)
    print(f"Project root   : {PROJECT_ROOT}")
    print(f"Knowledge base : {KNOWLEDGE_BASE_DIR} (exists: {KNOWLEDGE_BASE_DIR.exists()})")
    for label, folder in KNOWLEDGE_BASE_FOLDERS.items():
        print(f"  {label:<9}: {folder} (exists: {folder.exists()})")
    print(f"Index folder   : {INDEX_DIR} (exists: {INDEX_DIR.exists()})")
    print(f"Database file  : {DATABASE_PATH}")
    print(f"Chunk size     : {CHUNK_SIZE_WORDS} words, overlap {CHUNK_OVERLAP_WORDS}")
    print(f"Retrieval      : top {TOP_K}, threshold {SIMILARITY_THRESHOLD}")
    print(f"LLM            : {OLLAMA_MODEL} at {OLLAMA_BASE_URL}")
    print(f"Ticket statuses: {TICKET_STATUSES}")